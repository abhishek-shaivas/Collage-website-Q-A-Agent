# 18. DETECT TOPIC
# ============================================================

def detect_topic(question):

    q = question.lower()

    scores = {}

    for topic, keywords in QUESTION_TOPICS.items():

        score = 0

        for keyword in keywords:

            if keyword in q:
                score += 1

        scores[topic] = score

    best_topic = max(
        scores,
        key=scores.get
    )

    if scores[best_topic] == 0:

        return "general"

    return best_topic


