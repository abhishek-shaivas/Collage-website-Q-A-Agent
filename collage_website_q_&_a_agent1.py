def build_search_content():

    global website_content

    website_content = []

    for page in college_pages:

        text = page["text"]

        words = text.split()

        start = 0

        chunk_count = 0

        while (
            start < len(words)
            and chunk_count < MAX_CHUNKS_PER_PAGE
        ):

            chunk_words = words[
                start:start + CHUNK_WORDS
            ]

            chunk = " ".join(
                chunk_words
            )

            if len(chunk) >= 80:

                website_content.append({

                    "text": chunk,

                    "url": page["url"],

                    "title": page["title"]

                })

                chunk_count += 1

            start += CHUNK_WORDS

    print(
        "Search chunks:",
        len(website_content)
    )


