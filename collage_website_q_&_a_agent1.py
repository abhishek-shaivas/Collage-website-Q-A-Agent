# 15. CRAWL WEBSITE
# ============================================================

def crawl_website():

    global base_domain
    global college_pages
    global visited_urls

    college_pages = []

    visited_urls = set()

    start_url = normalize_url(
        COLLEGE_URL
    )

    base_domain = get_domain(
        start_url
    )

    queue = deque()

    queue.append(
        start_url
    )

    print()
    print("=" * 70)
    print("STARTING MITT WEBSITE CRAWLER")
    print("=" * 70)

    while (
        queue
        and len(college_pages) < MAX_PAGES
    ):

        current_url = queue.popleft()

        current_url = normalize_url(
            current_url
        )

        if not current_url:
            continue

        if current_url in visited_urls:
            continue

        if not same_domain(current_url):
            continue

        if not valid_url(current_url):
            continue

        visited_urls.add(
            current_url
        )

        print(
            f"\n[{len(college_pages)+1}/{MAX_PAGES}] "
            f"{current_url}"
        )

        response = download_page(
            current_url
        )

        if response is None:
            continue

        final_url = normalize_url(
            response.url
        )

        if final_url:

            current_url = final_url

        page = extract_page(
            current_url,
            response
        )

        if page:

            college_pages.append(
                page
            )

            print(
                "   ✓ Saved:",
                page["title"]
            )

        links = extract_links(
            current_url,
            response
        )

        for link in links:

            if link in visited_urls:
                continue

            if link in queue:
                continue

            if len(queue) >= MAX_PAGES * 3:
                break

            queue.append(link)

        time.sleep(0.05)

    print()
    print("=" * 70)
    print("CRAWLING FINISHED")
    print("=" * 70)

    print(
        "Pages loaded:",
        len(college_pages)
    )

    print(
        "URLs visited:",
        len(visited_urls)
    )

    return college_pages


