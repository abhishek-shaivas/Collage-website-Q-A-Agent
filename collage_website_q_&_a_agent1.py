# 20. EXTRACT RELEVANT SENTENCES
# ============================================================

def extract_relevant_sentences(
    question,
    results
):

    if not results:
        return []

    topic = detect_topic(
        question
    )

    topic_keywords = QUESTION_TOPICS.get(
        topic,
        []
    )

    question_words = set(
        re.findall(
            r"[a-zA-Z]{4,}",
            question.lower()
        )
    )

    sentences = []

    for item in results:

        text = item["text"]

        parts = re.split(
            r"(?<=[.!?])\s+",
            text
        )

        for sentence in parts:

            sentence = sentence.strip()

            if len(sentence) < 35:
                continue

            lower = sentence.lower()

            score = 0

            for keyword in topic_keywords:

                if keyword in lower:
                    score += 4

            for word in question_words:

                if word in lower:
                    score += 2

            if score > 0:

                sentences.append(
                    (
                        score,
                        sentence,
                        item["url"]
                    )
                )

    sentences.sort(
        key=lambda x: x[0],
        reverse=True
    )

    final_sentences = []

    seen = set()

    for score, sentence, url in sentences:

        normalized = re.sub(
            r"\W+",
            " ",
            sentence.lower()
        ).strip()

        if normalized in seen:
            continue

        seen.add(normalized)

        final_sentences.append(
            (
                sentence,
                url
            )
        )

        if len(final_sentences) >= 8:
            break

    return final_sentences


