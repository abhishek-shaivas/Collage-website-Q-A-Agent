def extract_page(url, response):

    try:

        soup = BeautifulSoup(
            response.text,
            "html.parser"
        )

        for tag in soup.find_all([
            "script",
            "style",
            "noscript",
            "svg",
            "canvas",
            "iframe",
            "form",
            "nav",
            "footer",
            "header"
        ]):

            tag.decompose()

        title = ""

        if soup.title:

            title = soup.title.get_text(
                " ",
                strip=True
            )

        main = soup.find("main")

        if main:

            text = main.get_text(
                " ",
                strip=True
            )

        else:

            body = soup.find("body")

            if body:

                text = body.get_text(
                    " ",
                    strip=True
                )

            else:

                text = soup.get_text(
                    " ",
                    strip=True
                )

        text = clean_text(text)

        if len(text) < MIN_TEXT_LENGTH:
            return None

        return {

            "url": url,
            "title": title,
            "text": text

        }

    except Exception as e:

        print(
            "EXTRACTION ERROR:",
            str(e)
        )

        return None


