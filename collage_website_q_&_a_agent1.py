def clean_answer_sentence(sentence):

    sentence = sentence.strip()

    sentence = re.sub(
        r"\s+",
        " ",
        sentence
    )

    unwanted_phrases = [

        "skip to main content",
        "click here to apply",
        "read more",
        "learn more",
        "cookie policy",
        "privacy policy",
        "terms and conditions",
        "follow us on",
        "all rights reserved",
        "contact us",
        "contact our team",
        "request info",
        "application form"

    ]

    lower_sentence = sentence.lower()

    for phrase in unwanted_phrases:

        if phrase in lower_sentence:
            return ""

    return sentence


