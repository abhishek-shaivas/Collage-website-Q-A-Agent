def get_domain(url):

    try:

        hostname = urlparse(url).hostname

        if not hostname:
            return ""

        hostname = hostname.lower()

        if hostname.startswith("www."):
            hostname = hostname[4:]

        return hostname

    except Exception:

        return ""


# ============================================================
# 9. SAME DOMAIN
# ============================================================

def same_domain(url):

    domain = get_domain(url)

    if not domain:
        return False

    if not base_domain:
        return False

    return (
        domain == base_domain
        or domain.endswith("." + base_domain)
    )


