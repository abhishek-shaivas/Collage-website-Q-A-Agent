# 14. EXTRACT LINKS
# ============================================================

def extract_links(page_url, response):

    links = []

    try:

        soup = BeautifulSoup(
            response.text,
            "html.parser"
        )

        for tag in soup.find_all("a"):

            href = tag.get("href")

            if not href:
                continue

            href = href.strip()

            if href.startswith((
                "#",
                "mailto:",
                "tel:",
                "javascript:",
                "whatsapp:"
            )):
                continue

            absolute = urljoin(
                page_url,
                href
            )

            absolute = urldefrag(
                absolute
            )[0]

            absolute = normalize_url(
                absolute
            )

            if not absolute:
                continue

            if not same_domain(absolute):
                continue

            if not valid_url(absolute):
                continue

            links.append(absolute)

    except Exception as e:

        print(
            "LINK ERROR:",
            str(e)
        )

    return list(
        dict.fromkeys(links)
    )


